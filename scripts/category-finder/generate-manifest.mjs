// Run manually (not part of `npm run build`, not run in CI):
//
//   node scripts/category-finder/generate-manifest.mjs
//
// Thin CLI wrapper: reads the gitignored snapshot
// (.snapshot/catalogue-snapshot.json, produced by fetch-catalogue-snapshot.mjs)
// plus the committed authoritative-category-ids.json, delegates the actual
// classification/reconciliation to lib/generateManifestCore.mjs (pure, no
// file I/O, directly unit-tested with fixtures), and writes:
//   - src/config/generated/categoryFinderManifest.js
//   - src/config/generated/parentGroupManifest.js
//   - src/config/generated/reconciliation.js
//
// Aborts WITHOUT writing anything if:
//   - the snapshot fails schema validation (missing/invalid stats), or
//   - the generated leaf/parent classification doesn't reconcile EXACTLY
//     against authoritative-category-ids.json (missing, duplicate, or
//     unexpected IDs) -- reconciling a generated file only against itself
//     would let an incomplete snapshot validate its own incompleteness.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { FAMILIES, LEAF_FAMILY_MAP, LEAF_OVERRIDES } from "./families.js";
import { SchemaError } from "./lib/schema.mjs";
import { ReconciliationError } from "./lib/reconcile.mjs";
import { HierarchyError } from "./lib/hierarchy.mjs";
import { generateManifestCore } from "./lib/generateManifestCore.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SNAPSHOT_PATH = path.join(__dirname, ".snapshot", "catalogue-snapshot.json");
const AUTHORITATIVE_PATH = path.join(__dirname, "authoritative-category-ids.json");
const OUT_MANIFEST = path.join(__dirname, "../../src/config/generated/categoryFinderManifest.js");
const OUT_PARENT_MANIFEST = path.join(__dirname, "../../src/config/generated/parentGroupManifest.js");
const OUT_RECONCILIATION = path.join(__dirname, "../../src/config/generated/reconciliation.js");

function main() {
  if (!fs.existsSync(SNAPSHOT_PATH)) {
    console.error(`No snapshot found at ${SNAPSHOT_PATH}. Run 'npm run category-finder:fetch' first.`);
    process.exit(1);
  }
  if (!fs.existsSync(AUTHORITATIVE_PATH)) {
    console.error(`No authoritative inventory found at ${AUTHORITATIVE_PATH}. This file must be committed and kept current.`);
    process.exit(1);
  }

  const snapshot = JSON.parse(fs.readFileSync(SNAPSHOT_PATH, "utf8"));
  const authoritative = JSON.parse(fs.readFileSync(AUTHORITATIVE_PATH, "utf8"));

  const { leafManifest, parentManifest, reconciliation } = generateManifestCore(snapshot, authoritative, {
    families: FAMILIES,
    leafFamilyMap: LEAF_FAMILY_MAP,
    leafOverrides: LEAF_OVERRIDES,
  });

  const manifestSource = `// AUTO-GENERATED by scripts/category-finder/generate-manifest.mjs -- do not hand-edit.
// Source snapshot fetched: ${snapshot.fetchedAt}
// Reconciled against scripts/category-finder/authoritative-category-ids.json.
export const CATEGORY_FINDER_MANIFEST = ${JSON.stringify(leafManifest, null, 2)};
`;
  const parentManifestSource = `// AUTO-GENERATED by scripts/category-finder/generate-manifest.mjs -- do not hand-edit.
export const PARENT_GROUP_MANIFEST = ${JSON.stringify(parentManifest, null, 2)};
`;
  const reconciliationSource = `// AUTO-GENERATED by scripts/category-finder/generate-manifest.mjs -- do not hand-edit.
export const RECONCILIATION = ${JSON.stringify(reconciliation, null, 2)};
`;

  fs.writeFileSync(OUT_MANIFEST, manifestSource);
  fs.writeFileSync(OUT_PARENT_MANIFEST, parentManifestSource);
  fs.writeFileSync(OUT_RECONCILIATION, reconciliationSource);
  console.log(`Reconciled leaves: ${JSON.stringify(reconciliation)}. Wrote manifest + parent manifest + reconciliation.`);
}

try {
  main();
} catch (err) {
  if (err instanceof SchemaError || err instanceof ReconciliationError || err instanceof HierarchyError) {
    console.error(`generate-manifest FAILED (${err.name}):\n${err.message}`);
  } else {
    console.error("generate-manifest failed with an unexpected error:", err);
  }
  process.exit(1);
}
