// Run manually, AFTER verify-filter-mappings.mjs:
//
//   node scripts/category-finder/promote-runtime-enabled.mjs
//
// This is the SEPARATE, explicit business-approval step the two-gate design
// has always required: filterMappingsValidated (set only by
// verify-filter-mappings.mjs, technical/API correctness) and runtimeEnabled
// (set only here, "approved for customers to see") must never be the same
// automatic side effect of one script -- a category can be fully verified
// and still deliberately held back, and that decision needs its own visible,
// re-runnable step, not to be buried inside the verifier.
//
// Promotes every entry where filterMappingsValidated === true and
// runtimeEnabled !== true. Curated overrides (PE-02) are left untouched --
// their runtimeEnabled is part of the hand-authored override in families.js,
// not something this script should second-guess.

import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MANIFEST_PATH = path.join(__dirname, "../../src/config/generated/categoryFinderManifest.js");
const PARENT_MANIFEST_PATH = path.join(__dirname, "../../src/config/generated/parentGroupManifest.js");

function serializeManifest(manifest) {
  return `// AUTO-GENERATED by scripts/category-finder/generate-manifest.mjs, then
// PATCHED by scripts/category-finder/verify-filter-mappings.mjs, then
// PROMOTED by scripts/category-finder/promote-runtime-enabled.mjs -- do not hand-edit.
export const CATEGORY_FINDER_MANIFEST = ${JSON.stringify(manifest, null, 2)};
`;
}

function serializeParentManifest(manifest) {
  return `// AUTO-GENERATED by scripts/category-finder/generate-manifest.mjs, then
// PATCHED by scripts/category-finder/verify-parent-mappings.mjs, then
// PROMOTED by scripts/category-finder/promote-runtime-enabled.mjs -- do not hand-edit.
export const PARENT_GROUP_MANIFEST = ${JSON.stringify(manifest, null, 2)};
`;
}

function promoteEntries(entries, promotedAt) {
  let promoted = 0;
  let alreadyEnabled = 0;
  let notEligible = 0;
  const patched = Object.fromEntries(
    entries.map(([categoryId, entry]) => {
      if (entry.finderMode === "curated") return [categoryId, entry]; // never touched here
      if (entry.runtimeEnabled === true) {
        alreadyEnabled += 1;
        return [categoryId, entry];
      }
      if (entry.filterMappingsValidated !== true) {
        notEligible += 1;
        return [categoryId, entry];
      }
      promoted += 1;
      return [
        categoryId,
        {
          ...entry,
          runtimeEnabled: true,
          dataQualityNotes: [...entry.dataQualityNotes, `Runtime-enabled by explicit promotion step at ${promotedAt}.`],
        },
      ];
    })
  );
  return { patched, promoted, alreadyEnabled, notEligible };
}

async function main() {
  if (!fs.existsSync(MANIFEST_PATH)) {
    console.error(`No manifest found at ${MANIFEST_PATH}. Run generate-manifest.mjs and verify-filter-mappings.mjs first.`);
    process.exit(1);
  }

  const promotedAt = new Date().toISOString();

  const { CATEGORY_FINDER_MANIFEST } = await import(`${pathToFileURL(MANIFEST_PATH).href}?t=${Date.now()}`);
  const leafResult = promoteEntries(Object.entries(CATEGORY_FINDER_MANIFEST), promotedAt);
  fs.writeFileSync(MANIFEST_PATH, serializeManifest(leafResult.patched));
  console.log(
    `Leaf promotion complete. Newly runtime-enabled: ${leafResult.promoted}. Already enabled: ${leafResult.alreadyEnabled}. Not eligible (not technically validated): ${leafResult.notEligible}. Wrote ${MANIFEST_PATH}.`
  );

  if (fs.existsSync(PARENT_MANIFEST_PATH)) {
    const { PARENT_GROUP_MANIFEST } = await import(`${pathToFileURL(PARENT_MANIFEST_PATH).href}?t=${Date.now()}`);
    const parentResult = promoteEntries(Object.entries(PARENT_GROUP_MANIFEST), promotedAt);
    fs.writeFileSync(PARENT_MANIFEST_PATH, serializeParentManifest(parentResult.patched));
    console.log(
      `Parent promotion complete. Newly runtime-enabled: ${parentResult.promoted}. Already enabled: ${parentResult.alreadyEnabled}. Not eligible: ${parentResult.notEligible}. Wrote ${PARENT_MANIFEST_PATH}.`
    );
  }
}

main().catch((err) => {
  console.error("promote-runtime-enabled failed:", err);
  process.exit(1);
});
