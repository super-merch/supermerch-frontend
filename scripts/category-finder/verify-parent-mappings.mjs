// Run manually, AFTER generate-manifest.mjs and (independently) after
// verify-filter-mappings.mjs has finished with the 297 leaves:
//
//   node scripts/category-finder/verify-parent-mappings.mjs
//
// The exhaustive live-verification pass for the 27 parent/group aggregate
// pages (e.g. "PX" Workwear, covering every PX-* leaf) -- the exact same
// checks verify-filter-mappings.mjs runs for leaves (every option of every
// question, all quantity/budget buckets, fresh baseline, sample-product
// correctness), reusing the identical verifyLeafMappings core. Kept as a
// separate script (not folded into verify-filter-mappings.mjs) because
// parents read/write a different file (parentGroupManifest.js, not
// categoryFinderManifest.js) and there are only 27 of them -- a single,
// un-batched run is small enough not to need VERIFY_OFFSET/LIMIT batching.
//
// This script ONLY sets filterMappingsValidated. It never touches
// runtimeEnabled -- see promote-runtime-enabled.mjs for parents too (it
// already reads PARENT_GROUP_MANIFEST the same way it reads
// CATEGORY_FINDER_MANIFEST).

import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { verifyLeafMappings } from "./lib/verifyFilterMappings.mjs";
import { mapWithConcurrency } from "./lib/concurrency.mjs";
import { fetchJsonWithRetry as fetchJsonWithRetryShared } from "./lib/httpRetry.mjs";

const API_BASE = process.env.SUPERMERCH_API_BASE || "https://api.supermerch.com.au";
const CONCURRENCY = 3;
const RETRY_DELAYS_MS = [500, 1500];
const REQUEST_TIMEOUT_MS = 20_000;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PARENT_MANIFEST_PATH = path.join(__dirname, "../../src/config/generated/parentGroupManifest.js");
const EVIDENCE_PATH = path.join(__dirname, ".evidence", "parentGroupVerificationEvidence.json");
const SUMMARY_PATH = path.join(__dirname, "parent-verification-summary.json");

const fetchJsonWithRetry = (url) => fetchJsonWithRetryShared(url, RETRY_DELAYS_MS, REQUEST_TIMEOUT_MS);

function serializeParentManifest(manifest) {
  return `// AUTO-GENERATED by scripts/category-finder/generate-manifest.mjs, then
// PATCHED by scripts/category-finder/verify-parent-mappings.mjs -- do not hand-edit.
// filterMappingsValidated reflects live, exhaustive verification against the
// real API, the identical checks run for leaves (see
// verify-filter-mappings.mjs / lib/verifyFilterMappings.mjs). runtimeEnabled
// is set by a SEPARATE step (promote-runtime-enabled.mjs), never by this
// script.
export const PARENT_GROUP_MANIFEST = ${JSON.stringify(manifest, null, 2)};
`;
}

async function main() {
  if (!fs.existsSync(PARENT_MANIFEST_PATH)) {
    console.error(`No parent manifest found at ${PARENT_MANIFEST_PATH}. Run generate-manifest.mjs first.`);
    process.exit(1);
  }

  const { PARENT_GROUP_MANIFEST } = await import(`${pathToFileURL(PARENT_MANIFEST_PATH).href}?t=${Date.now()}`);
  const entries = Object.entries(PARENT_GROUP_MANIFEST);
  const candidates = entries.filter(([, entry]) => entry.finderMode !== "excluded");
  const excluded = entries.filter(([, entry]) => entry.finderMode === "excluded");

  const liveManifest = { ...PARENT_GROUP_MANIFEST };
  const liveEvidence = {};

  function persist() {
    fs.mkdirSync(path.dirname(EVIDENCE_PATH), { recursive: true });
    fs.writeFileSync(PARENT_MANIFEST_PATH, serializeParentManifest(liveManifest));
    fs.writeFileSync(EVIDENCE_PATH, JSON.stringify({ generatedAt: new Date().toISOString(), categories: liveEvidence }, null, 2));

    const compact = {};
    for (const [id, evidence] of Object.entries(liveEvidence)) {
      compact[id] = {
        passed: evidence.passed,
        verifiedAt: evidence.verifiedAt,
        liveUnfilteredCount: evidence.liveUnfilteredCount,
        survivingQuestionIds: evidence.survivingQuestions.map((q) => q.id),
        removedQuestionIds: evidence.removedQuestionIds,
        questionOptionCounts: evidence.questions.map((q) => ({ id: q.id, optionsTested: q.options.length, optionsSurviving: q.survivingOptions.length })),
      };
    }
    fs.writeFileSync(SUMMARY_PATH, JSON.stringify({ generatedAt: new Date().toISOString(), categories: compact }, null, 2));
  }

  console.log(`Verifying ${candidates.length} parent/group pages (${excluded.length} already excluded, skipped) ...`);

  let done = 0;
  let validated = 0;
  let failed = 0;

  await mapWithConcurrency(candidates, CONCURRENCY, async ([categoryId, entry]) => {
    const evidence = await verifyLeafMappings({ categoryId, questions: entry.questions }, { fetchJson: fetchJsonWithRetry, apiBase: API_BASE });
    liveEvidence[categoryId] = evidence;

    if (evidence.passed) {
      validated += 1;
      liveManifest[categoryId] = {
        ...entry,
        questions: evidence.survivingQuestions,
        filterMappingsValidated: true,
        runtimeEnabled: false,
        dataQualityNotes: [
          ...entry.dataQualityNotes,
          `Live-verified ${evidence.questions.length} category-specific question(s) (${evidence.questions.reduce((s, q) => s + q.options.length, 0)} option(s) tested) + quantity/budget checks against the real API at ${evidence.verifiedAt}.` +
            (evidence.removedQuestionIds.length > 0 ? ` Removed question(s) that failed verification: ${evidence.removedQuestionIds.join(", ")}.` : ""),
        ],
      };
    } else {
      failed += 1;
      liveManifest[categoryId] = {
        ...entry,
        finderMode: "excluded",
        questions: [],
        filterMappingsValidated: false,
        runtimeEnabled: false,
        exclusionReason: evidence.belowMinimumQuestions
          ? `Live verification FAILED at ${evidence.verifiedAt}: only 1 question survived exhaustive checking, below the 2-question minimum to ship a real Finder.`
          : `Live verification FAILED at ${evidence.verifiedAt}: no question survived exhaustive checking.`,
        dataQualityNotes: [...entry.dataQualityNotes, `Live verification FAILED at ${evidence.verifiedAt}. See scripts/category-finder/parent-verification-summary.json.`],
      };
    }

    persist();
    done += 1;
    console.log(`  ...${done}/${candidates.length} (${validated} validated, ${failed} failed so far)`);
  });

  console.log(`Done. ${validated} validated, ${failed} failed, ${excluded.length} pre-excluded, out of ${entries.length} total parent/group pages. Wrote ${PARENT_MANIFEST_PATH}, ${SUMMARY_PATH} (committed), ${EVIDENCE_PATH} (gitignored, full detail).`);
}

main().catch((err) => {
  console.error("verify-parent-mappings failed:", err);
  process.exit(1);
});
